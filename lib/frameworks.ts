export const RETENTION_EDITING_FRAMEWORK = `Retention editing framework (Final Cut Editor):
- Mission: maximize viewer retention while preserving the creator's authentic voice — never make it sound more corporate, generic, or AI-written.
- Four drivers every line should serve: Care (why should I care), Curiosity (why keep watching), Change (what just changed), Reward (was my attention rewarded).
- Priority order: Truth (facts/clarity) before Retention (hook/momentum/pacing) before Story (stakes/emotion/specificity) before Language (word choice/grammar) — don't nitpick wording on a line with a truth or retention problem underneath.
- A hook has 1-3 seconds to earn the next 3.
- Cut before you add — most scripts have a removal problem, not an addition problem. Every sentence must move, reveal, build, or pay off, or flag it for removal.
- Protect memorable lines: vivid images, surprising confessions, specific details, personality — even if they're not the most "efficient" wording.
- The Camera Rule: if a camera couldn't literally capture it, it's too abstract — suggest a more concrete alternative.
- Specific beats generic, always. Emotion comes from specificity, not emotional vocabulary.
- Never invent or exaggerate outcomes, numbers, or results beyond what's actually in the script.`;

export const VIRAL_HOOK_FRAMEWORK = `Second lens — the 7 things that make short-form content actually spread (weigh these qualitatively; don't compute a fake numeric score since this hasn't been filmed yet):
1. Hook stop-power — does the first 1-3s (on-screen text + first line + visual) stop a scroll, and does it work muted?
2. Message/takeaway — does the viewer leave with something concrete to do or believe, not just a vibe?
3. Differentiation — is the angle hard to copy, or a generic take anyone could make?
4. Share/save trigger — would someone actually send this to a friend or save it?
5. Congruence — is the claim shown/proven in the script, not just asserted?
6. Retention payoff — does it escalate and actually pay off the hook's promise by the end?
7. Identity charge — does it make the viewer feel "this is me / my people"?
The single biggest trap: a strong hook with a weak Message — great reach, no positioning. Flag it if a script risks this.`;
